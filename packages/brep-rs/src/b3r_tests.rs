//! SLICE B3R: neighbours of the B3 common cases, probed against FreeCAD 26.3.0 RC1 (`Part.makeBox().common(Part.makeSphere())` with the
//! refine PartDesign applies, which is what the census measures) for face counts. Volumes are never changed: every built case here is
//! checked against an exact volume computed apart from both kernels (the area of disc x rectangle, integrated in z with breakpoints at
//! every edge and corner; a closed form for the cylinder).
//!
//! What FreeCAD does with the sphere of a ball kept from a box, as measured over about 1100 cases (block 30 x 20 x 10 and four other
//! blocks, tangent and off-centre, through every plane and corner): ONE sphere face per connected patch of the sphere inside the box,
//! except that the patch is parted wherever the sphere's seam half-meridian (the one in the plane through the axis and the x direction,
//! on the +x side) crosses it from the box's boundary to the box's boundary. A chord of the seam that ends at a pole is a slit, not a
//! cut; a chord that no other route round the patch avoids parts it. The pieces are the faces. A patch with a full ring round the axis
//! stays whole because no chord of the seam parts it, not because of the ring.
#![cfg(test)]
use crate::{build, ops};

type S = build::TSolid;

fn block(size: [f64; 3]) -> S {
    build::box_solid(size, [size[0] / 2.0, size[1] / 2.0, size[2] / 2.0], None)
}

fn ball(at: [f64; 3], r: f64) -> S {
    build::sphere_solid(at, r, [0.0, 0.0, 1.0])
}

fn close(a: f64, b: f64, rel: f64) -> bool {
    (a - b).abs() <= rel * b.abs().max(1.0)
}

/// Every cylinder tangent to two faces of the block and crossing a third (or none) is ONE wall face, as FreeCAD 26.3.0 RC1 cuts it:
/// 4 faces vertical, 4 and 3 faces horizontal. This kernel kept a second wall piece where the run of kept cells crossed the wall's seam.
#[test]
fn a_cylinder_tangent_on_two_sides_and_crossing_a_third_is_one_wall_like_freecad() {
    let a = block([30.0, 20.0, 10.0]);
    let vert = |cx: f64, cy: f64, r: f64| build::cylinder_solid([cx, cy, 5.0], r, 14.0, [0.0, 0.0, 1.0]);
    let mut cases: Vec<(String, S, usize, f64)> = Vec::new();
    for (x, vol) in [(1.0, 1770.4624916671185), (3.0, 2161.670741235378), (5.0, 2527.407804285415), (8.0, 2978.0915447965085), (9.0, 3082.8667467121913)] {
        cases.push((format!("cyl r10 x{x}"), vert(x, 10.0, 10.0), 4, vol));
    }
    for (y, vol) in [(1.0, 3834.069364682482), (3.0, 4428.255210767734), (5.0, 5006.031562746839)] {
        cases.push((format!("cyl r15 y{y}"), vert(15.0, y, 15.0), 4, vol));
    }
    for (x, f, vol) in [(3.0, 4, 1347.1487177940908), (5.0, 3, 1570.7963267948967), (8.0, 3, 1570.7963267948967)] {
        cases.push((format!("hcyl r5 x{x}"), build::cylinder_solid([x, 10.0, 5.0], 5.0, 24.0, [0.0, 1.0, 0.0]), f, vol));
    }
    for (label, t, fc, vol) in cases {
        let r = ops::boolean("intersect", &a, &t).unwrap_or_else(|| panic!("{label}: builds"));
        assert_eq!(r.faces().len(), fc, "{label}: FreeCAD face count");
        let v = build::solid_volume(&r);
        assert!(close(v, vol, 1e-11), "{label}: volume {v} vs {vol}");
        assert!(ops::edge_use_counts(&r.faces()).values().all(|&n| n == 2), "{label}: closed shell");
        let walls = r.faces().iter().filter(|f| matches!(f.borrow().surface, crate::geom::Surface::Cylinder(_))).count();
        assert_eq!(walls, 1, "{label}: one wall face");
        let m = crate::mesh::mesh_solid(&r, 0.05).unwrap_or_else(|| panic!("{label}: meshes"));
        assert!(ops::check_watertight(&m), "{label}: watertight mesh");
        crate::step::write_solid(&r, "b3r").unwrap_or_else(|e| panic!("{label}: STEP {e}"));
    }
}

/// A cylinder that crosses one face and is tangent to another near the wall's seam used to be refused: the block's face at y = 20 cuts
/// the wall, the face at x = 0 touches it, and FreeCAD leaves four faces.
#[test]
fn a_cylinder_crossing_one_face_and_tangent_to_another_is_four_faces() {
    let a = block([30.0, 20.0, 10.0]);
    // the radius within a percent of 10 is where the planar arrangement put the cylinder's arc and the block's edge the wrong way round at
    // their point of contact (both leave it straight up; one is the circle)
    for (r, at, vol) in [
        (10.0, [10.0, 17.0], 2161.6707412353776),
        (10.0, [10.0, 16.0], 2348.9192284588516),
        (10.0, [10.0, 18.0], 1968.1134270078815),
        (9.9, [9.9, 17.0], 2124.317051491905),
        (10.1, [10.1, 16.0], 2388.720107052532),
    ] {
        let t = build::cylinder_solid([at[0], at[1], 5.0], r, 14.0, [0.0, 0.0, 1.0]);
        let s = ops::boolean("intersect", &a, &t).unwrap_or_else(|| panic!("r{r} at {at:?} builds"));
        assert_eq!(s.faces().len(), 4, "r{r} at {at:?}");
        assert!(ops::edge_use_counts(&s.faces()).values().all(|&n| n == 2));
        let v = build::solid_volume(&s);
        assert!(close(v, vol, 1e-11), "r{r} at {at:?}: volume {v} vs {vol}");
    }
}

