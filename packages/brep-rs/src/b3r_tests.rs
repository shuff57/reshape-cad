fn check_ball(label: &str, size: [f64; 3], at: [f64; 3], r: f64, fc: usize, vol: f64, step: bool) {
    let a = block(size);
    let t = ball(at, r);
    let s = ops::boolean("intersect", &a, &t).unwrap_or_else(|| panic!("{label}: builds"));
    assert_eq!(s.faces().len(), fc, "{label}: FreeCAD face count");
    let v = build::solid_volume(&s);
    assert!(close(v, vol, 1e-8), "{label}: volume {v} vs exact {vol}");
    assert!(ops::edge_use_counts(&s.faces()).values().all(|&n| n == 2), "{label}: closed shell");
    let m = crate::mesh::mesh_solid(&s, 0.05).unwrap_or_else(|| panic!("{label}: meshes"));
    assert!(ops::check_watertight(&m), "{label}: watertight mesh");
    // no sphere face of the result may be a hull with two disconnected patches: each face is one connected piece
    for f in s.faces() {
        if let crate::geom::Surface::Sphere(sp) = &f.borrow().surface {
            if sp.trim.is_hull() {
                assert!(sp.hull_measure().is_some(), "{label}: a sphere face that measures");
            }
        }
    }
    if step {
        let _ = crate::step::write_solid(&s, "b3r");
    }
}

