-- reshape-cad Part Design: the app-local store.
--
-- READ THIS FIRST. The CAD document itself is NOT in SQL. It is the Rust `Document` type in `reshape-doc`
-- (architecture.md section 4), serialised to canonical JSON inside a `.reshape` zip. SQLite cannot live inside
-- the core: SPEC-brep-kernel-rs §2 forbids C/C++ dependencies in the wasm build, and the core is one crate tree
-- for both shells. So the document is a file, and this schema is the small store the APP keeps beside it:
-- recent files, preferences, autosave snapshots, the per-feature build cache and the hole-standard tables.
--
-- Dialect: SQLite 3.35+ (rusqlite, `bundled` feature, desktop shell only). The browser shell mirrors the same
-- logical tables in IndexedDB (object store per table, same column names, same keys) through packages/studio;
-- the Rust core never touches storage directly, it hands the shell typed rows.
--
-- Access rules: single user, local file (`$XDG_DATA_HOME/reshape/store.sqlite`, mode 0600). There is no
-- row-level security and no per-query authorisation check because there is no second principal. The day a sync
-- layer appears, `documents.owner_id` is the column that becomes the owner key; it exists now so that migration is
-- an `update`, not a rewrite.
--
-- Times are ISO-8601 UTC text (`strftime('%Y-%m-%dT%H:%M:%fZ','now')`), always; SQLite has no timestamptz.
-- Ids are UUID v4 text generated by the app (no gen_random_uuid in SQLite). Money: none, nothing is sold here.

pragma journal_mode = wal;
pragma foreign_keys = on;

-- Schema version for the store itself (the document has its own `schema` field).
create table if not exists store_migrations (
  version     integer primary key,
  applied_at  text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
insert or ignore into store_migrations (version) values (1);

-- Recent and known documents. One row per file the app has opened or saved. `document_id` is the Uuid inside
-- document.json, so a file that is moved or copied is still recognised; `path` is where it was last seen.
create table if not exists documents (
  id            text primary key,                           -- uuid, the document's own id
  owner_id      text not null default 'local',              -- future sync owner; see header
  path          text,                                       -- absolute path (desktop) or OPFS key (browser); null = never saved
  label         text not null,
  schema        integer not null check (schema >= 1),       -- document.json schema version at last open
  size_bytes    integer not null default 0 check (size_bytes >= 0),
  thumbnail     blob,                                       -- png, at most 64 KiB; enforced by the app
  last_opened_at text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  last_saved_at  text,
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index if not exists documents_recent on documents (owner_id, last_opened_at desc);
create unique index if not exists documents_path on documents (path) where path is not null;

-- Autosave and crash recovery. One snapshot per committed transaction since the last save, pruned on save and
-- capped per document by the app (default 200). `document_json` is the same canonical JSON as document.json.
create table if not exists snapshots (
  id            text primary key,                           -- uuid
  document_id   text not null references documents(id) on delete cascade,
  seq           integer not null check (seq >= 0),          -- transaction counter within the session
  transaction_label text not null,                          -- "Pad", "Edit Sketch", "Set Params.width"
  document_json text not null,
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  unique (document_id, seq)
);
create index if not exists snapshots_by_doc on snapshots (document_id, created_at desc);

-- Per-feature build cache. The key is a hash of the LOWERED ModelDoc JSON prefix up to and including the feature
-- (architecture.md section 6), never a float result, so the browser and the desktop produce the same key for the
-- same document and a last-ulp libm difference cannot poison it. Value is the mesh (positions, index, face ranges)
-- and the measurement the viewport needs; the kernel is the authority and the cache is dropped whenever the kernel
-- version string changes.
create table if not exists build_cache (
  input_hash    text primary key,                           -- blake3 hex of the lowered JSON prefix
  kernel_version text not null,                             -- brep_rs::version()
  mesh          blob not null,                              -- packed f32 positions + u32 index + face ranges
  volume        real,
  bbox          text,                                       -- JSON [[minx,miny,minz],[maxx,maxy,maxz]]
  face_count    integer,
  byte_size     integer not null check (byte_size >= 0),
  last_used_at  text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  created_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
create index if not exists build_cache_lru on build_cache (last_used_at);
create index if not exists build_cache_kernel on build_cache (kernel_version);

-- Preferences: a key/value bag with a JSON value, one row per key. Keys are dotted ("units.system",
-- "view.navigation", "theme", "recompute.on_change"). The app owns the list of keys; the store does not validate.
create table if not exists preferences (
  key           text primary key,
  value_json    text not null,
  updated_at    text not null default (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

-- Hole standards (features.csv "Hole: standard sizes table", needs-app). Seeded from PUBLIC standards tables
-- (ISO 273 clearance, ISO 262 / ISO 724 metric thread pitches, ASME B18.2.8 counterbores, ANSI B1.1 UNC/UNF),
-- typed in from the standards, not copied from FreeCAD's tables. All lengths in mm, angles in degrees.
create table if not exists hole_standards (
  id                  integer primary key,
  standard            text not null check (standard in ('ISO','ISOmetric','ISOmetricfine','UNC','UNF','UNEF','NPT','BSP','BSW','BSF','JIS')),
  size                text not null,                        -- "M6", "1/4-20"
  nominal_d           real not null check (nominal_d > 0),  -- thread major diameter
  pitch               real check (pitch > 0),               -- mm per turn (null for NPT taper)
  tap_drill_d         real check (tap_drill_d > 0),
  clearance_close_d   real check (clearance_close_d > 0),
  clearance_normal_d  real check (clearance_normal_d > 0),
  clearance_loose_d   real check (clearance_loose_d > 0),
  counterbore_d       real check (counterbore_d > 0),
  counterbore_depth   real check (counterbore_depth > 0),
  countersink_d       real check (countersink_d > 0),
  countersink_angle   real not null default 90 check (countersink_angle > 0 and countersink_angle < 180),
  unique (standard, size)
);
create index if not exists hole_standards_by_standard on hole_standards (standard, nominal_d);

-- Hard constraints the recon found, and where they live:
--   * a transaction sequence is unique per document        -> snapshots unique (document_id, seq)
--   * one path maps to one document                        -> documents_path partial unique index
--   * a cache row never outlives its kernel                 -> app deletes `where kernel_version <> ?` on load
--   * cycles in expressions, unit mismatches, over-constrained sketches are DOCUMENT rules, enforced in
--     reshape-expr / reshape-sketch at edit time, not here; the store never sees an invalid document as "valid",
--     it only stores bytes.
