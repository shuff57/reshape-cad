// Writes ../KERNEL-WORKLIST.md and kernel-gaps/<id>.mjs from the scoreboard + classifications.json.
// A variant is a kernel item when its classification is real-kernel-bug / real-kernel-gap, or carries a `kernel` block (a script-layer
// fix that left the kernel's own behaviour behind it: the script now refuses the input, the kernel still mishandles it).
// Every number in the document is measured in the run that just finished; the explanation text comes from classifications.json.
import { mkdirSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { HERE, measureScript, measureDoc, patchDoc, load } from './lib.mjs';

const RANK = { 'real-kernel-bug': 0, 'real-kernel-gap': 1 };
const fmt = (x) => JSON.stringify(Array.isArray(x) ? x.map((v) => (typeof v === 'number' ? +v.toPrecision(10) : v)) : typeof x === 'number' ? +x.toPrecision(10) : x);

export async function writeWorklist(board) {
  const dir = path.join(HERE, 'kernel-gaps');
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (f.endsWith('.mjs')) rmSync(path.join(dir, f));
  const items = [];
  for (const p of board.variants) {
    const c = p.classification;
    if (!c || p.status === 'MATCH') continue;
    const k = c.kernel ?? (c.class in RANK ? c : null);
    if (k) items.push({ p, k, c });
  }
  items.sort((a, b) => (RANK[a.k.class] - RANK[b.k.class]) || ((a.k.severity ?? 9) - (b.k.severity ?? 9)) || a.p.id.localeCompare(b.p.id));

  const lines = [];
  lines.push('# Kernel worklist from the variant sweep', '');
  lines.push(`Generated by \`variants/compare-variants.mjs\` (${board.generatedAt}) from \`variants/scoreboard.json\` and \`variants/classifications.json\`. Reference: FreeCAD 26.3.0 RC1 headless; ours: reSHape Script on the real brep-rs wasm. Nothing here edits the kernel.`, '');
  lines.push('Ranking: **real-kernel-bug** first (the kernel returns a solid that is wrong, silently, with no refusal sentence), then **real-kernel-gap** (a sentence refusal, or a topology difference with the solid itself right, for a part FreeCAD builds). Inside a class, by severity (1 = worst), then by name.', '');
  lines.push('Every entry has a runnable minimal reproduction, `node docs/replica/freecad/gauntlet/variants/kernel-gaps/<id>.mjs` (real Node: `export PATH=$HOME/.local/opt/node-v24.21.0-linux-x64/bin:$PATH`). It rebuilds the case on the real kernel, prints what the kernel did next to FreeCAD\'s numbers for the same part (from `variants/refs/`), and exits 0 while the problem still reproduces, 1 once it no longer does (the entry is then stale).', '');
  lines.push(`Run summary: ${board.summary.total} variants, ${board.summary.MATCH ?? 0} MATCH; ${items.length} kernel entries below.`, '');
  if (!items.length) lines.push('_No kernel-class entries in this run._');
  let n = 0;
  for (const { p, k, c } of items) {
    n++;
    const live = await liveKernelResult(p, k);
    lines.push(`## ${n}. [${k.class}] ${k.title ?? p.id}`, '');
    lines.push(`- severity: ${k.severity ?? '-'}   variant: \`${p.id}\` (${p.piece}) -- ${p.desc}`);
    lines.push(`- script as written: \`${p.oursSource ?? '(sketch rows, see kernel-gaps/' + p.id + '.mjs)'}\``);
    if (k.baseScript) lines.push(`- reached through a patched ModelDoc, because the script layer now refuses the input (${c.class}${c.fixed ? ', fixed' : ''}): base script \`${k.baseScript}\` with the first \`${k.patch.kind}\` feature set to \`${JSON.stringify(k.patch.set)}\``);
    if (live.outcome === 'built') {
      lines.push(`- kernel result: volume ${fmt(live.volume)}, faces ${live.faces}, bbox ${fmt(live.bbox)}, centre of mass ${fmt(live.com)}, mesh volume ${fmt(live.meshVolume)}`);
      if (live.ref) lines.push(`- FreeCAD: volume ${fmt(live.ref.volume)}, faces ${live.ref.faces}, bbox ${fmt(live.ref.bbox)}, centre of mass ${fmt(live.ref.com)}`);
    } else if (live.sketch) lines.push(`- kernel result: ${live.sketch}`);
    else lines.push(`- kernel result: refused in a sentence: "${live.refusal}"`);
    lines.push(`- evidence: ${k.evidence}`);
    lines.push(`- reproduce: \`node docs/replica/freecad/gauntlet/variants/kernel-gaps/${p.id}.mjs\``, '');
    writeFileSync(path.join(dir, `${p.id}.mjs`), repro(p, k));
  }
  writeFileSync(path.join(HERE, '..', 'KERNEL-WORKLIST.md'), lines.join('\n') + '\n');
  return items.length;
}

async function liveKernelResult(p, k) {
  const { readFileSync, existsSync } = await import('node:fs');
  const refFile = path.join(HERE, 'refs', `ref-${k.ref ?? p.id}.json`);
  const ref = existsSync(refFile) ? JSON.parse(readFileSync(refFile, 'utf8')) : null;
  if (p.kind === 'sketch') return { outcome: 'sketch', sketch: `refused: "${p.sentence}"` };
  let r;
  if (k.baseScript) {
    const { runScript } = await load();
    r = await measureDoc(patchDoc(runScript(k.baseScript).doc, k.patch.kind, k.patch.set));
  } else r = await measureScript(p.oursSource);
  return { ...r, ref };
}

function repro(p, k) {
  const head = `// Minimal reproduction: ${p.id} -- ${p.desc}
// class: ${k.class}${k.severity ? ` (severity ${k.severity})` : ''}. Generated by variants/worklist.mjs from the variant's own source, unchanged.
//   node docs/replica/freecad/gauntlet/variants/kernel-gaps/${p.id}.mjs        (exit 0 = still reproduces, 1 = it does not any more)
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
`;
  if (p.kind === 'sketch') {
    return head + `import { load } from '../lib.mjs';
import { VARIANTS } from '../defs.mjs';

const v = VARIANTS.find((x) => x.id === ${JSON.stringify(p.id)});
const { SketchSession2D, brep } = await load();
console.log('geometry :', JSON.stringify(v.oursGeom));
console.log('rules    :', JSON.stringify(v.oursRules));
const s = new SketchSession2D(); s.loadFromBytes(brep);
const open = s.open(v.oursGeom, v.oursRules);
const solved = open ? false : s.solve();
console.log('open     :', open ?? 'ok');
console.log('solve    :', solved, solved ? '' : '-- ' + (open ?? s.lastError()));
const reproduces = !solved;
console.log(reproduces ? 'REPRODUCES: the sketch solver refuses what FreeCAD solves' : 'DOES NOT REPRODUCE: it solves now');
process.exit(reproduces ? 0 : 1);
`;
  }
  const build = k.baseScript
    ? `import { measureDoc, patchDoc, load } from '../lib.mjs';
const BASE = ${JSON.stringify(k.baseScript)};
const PATCH = ${JSON.stringify(k.patch)};
const { runScript } = await load();
const r = await measureDoc(patchDoc(runScript(BASE).doc, PATCH.kind, PATCH.set));
console.log('base script   :', BASE);
console.log('then patched  :', 'first', PATCH.kind, 'feature <-', JSON.stringify(PATCH.set), '(a ModelDoc edit: the script layer refuses this input)');`
    : `import { measureScript } from '../lib.mjs';
const SRC = ${JSON.stringify(p.oursSource)};
const r = await measureScript(SRC);
console.log('script  :', SRC);`;
  return head + `${build}
const refFile = path.join(path.dirname(fileURLToPath(import.meta.url)), '../refs/ref-${k.ref ?? p.id}.json');
const ref = existsSync(refFile) ? JSON.parse(readFileSync(refFile, 'utf8')) : null;
console.log('kernel  :', r.outcome, r.outcome === 'built' ? JSON.stringify({ volume: r.volume, faces: r.faces, bbox: r.bbox, com: r.com, meshVolume: r.meshVolume }) : '-- ' + r.refusal);
console.log('FreeCAD :', ref ? JSON.stringify({ volume: ref.volume, faces: ref.faces, bbox: ref.bbox, com: ref.com }) : '(refs/ref-${k.ref ?? p.id}.json missing: run compare-variants.mjs first)');
let reproduces;
if (r.outcome !== 'built') reproduces = true; // a refusal sentence for a part FreeCAD builds is the gap itself
else if (!ref) reproduces = false;
else {
  const rel = (a, b) => Math.abs(a - b) / Math.max(Math.abs(b), Number.EPSILON);
  const bd = Math.max(...ref.bbox.map((x, i) => Math.abs(x - r.bbox[i])));
  const cd = ref.com && r.com ? Math.max(...ref.com.map((x, i) => Math.abs(x - r.com[i]))) : 0;
  reproduces = rel(r.volume, ref.volume) > 1e-6 || bd > 1e-6 || ref.faces !== r.faces || cd > 0.02 || rel(r.meshVolume, r.volume) > 5e-3;
}
console.log(reproduces ? 'REPRODUCES: the kernel differs from FreeCAD / refuses (see above)' : 'DOES NOT REPRODUCE: the kernel matches FreeCAD now');
process.exit(reproduces ? 0 : 1);
`;
}
