// Builds ../LAYER-CONTRACT.md and ../LAYER-CONTRACT-ROWS.md from the 13 group files, the latest critic verdict per
// group, contract-overrides.json (post-fix-round findings) and contract-notes.json (scope + brep-rs comparison).
//   node build-contract.mjs                 write both files
//   node build-contract.mjs --diff A B      compare two directories of <group>.json (e.g. the contract measured on two kernels)
// Nothing here is measured: it only collects what the group files and the critics said, and fails if the
// comparison table in contract-notes.json disagrees with the rows it cites.
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUTDIR = path.dirname(HERE);
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const GROUPS = Object.keys(readJson(path.join(HERE, 'contract-commands.json')).groups);
const rowsOf = (dir, g) => { const d = readJson(path.join(dir, `${g}.json`)); return Array.isArray(d) ? d : d.rows; };
const one = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();
const cut = (s, n) => (one(s).length > n ? one(s).slice(0, n - 1) + '…' : one(s));
const esc = (s) => String(s).replace(/\|/g, '\\|');

if (process.argv[2] === '--diff') {
  const [A, B] = [path.resolve(process.argv[3]), path.resolve(process.argv[4])];
  let changed = 0;
  for (const g of GROUPS) {
    const a = new Map(rowsOf(A, g).map((r) => [r.feature, r.status])), b = new Map(rowsOf(B, g).map((r) => [r.feature, r.status]));
    for (const [f, s] of a) {
      if (!b.has(f)) { console.log(`REMOVED  ${g}: ${cut(f, 120)} (was ${s})`); changed++; }
      else if (b.get(f) !== s) { const promo = s === 'refused' && b.get(f) === 'supported' ? ' -> promote only after the guard fuzz and saved FreeCAD results agree' : b.get(f) === 'wrong' ? ' -> LOUD: add or restore a guard before anything ships' : ''; console.log(`${s} -> ${b.get(f)}  ${g}: ${cut(f, 110)}${promo}`); changed++; }
    }
    for (const [f, s] of b) if (!a.has(f)) { console.log(`NEW ${s}  ${g}: ${cut(f, 120)}`); changed++; }
  }
  console.log(`${changed} row change(s)`); process.exit(0);
}

const overrides = readJson(path.join(HERE, 'contract-overrides.json'));
const notes = readJson(path.join(HERE, 'contract-notes.json'));

// latest finished verdict per group (<g>.json, <g>.round2.json, <g>.round3.json ...)
const vdir = path.join(HERE, 'critic-verdicts');
function verdictOf(g) {
  const files = readdirSync(vdir).filter((f) => f === `${g}.json` || (f.startsWith(`${g}.round`) && f.endsWith('.json')))
    .sort((x, y) => (x === `${g}.json` ? 0 : +x.match(/round(\d+)/)[1]) - (y === `${g}.json` ? 0 : +y.match(/round(\d+)/)[1]));
  const done = files.map((f) => ({ f, v: readJson(path.join(vdir, f)) })).filter((x) => x.v.verdict === 'accepted' || x.v.verdict === 'not-accepted');
  return { all: done, last: done[done.length - 1] };
}

const data = {};
for (const g of GROUPS) {
  const rows = rowsOf(HERE, g).map((r, i) => ({ n: i + 1, feature: r.feature, status: r.status, sentence: r.refusalSentence, note: null }));
  for (const o of overrides.overrides.filter((x) => x.group === g)) {
    const r = rows[o.row - 1];
    if (!r) throw new Error(`override: ${g} has no row ${o.row}`);
    r.note = `OVERRIDDEN ${r.status} -> ${o.status}: ${o.reason} (${o.source})`; r.status = o.status;
  }
  for (const a of overrides.addedRows.filter((x) => x.group === g)) rows.push({ n: rows.length + 1, feature: a.feature, status: a.status, sentence: null, note: `ADDED by the final critic, not in ${g}.json: ${a.evidence} (${a.source})` });
  const counts = { supported: 0, refused: 0, wrong: 0, unsupported: 0 };
  for (const r of rows) counts[r.status] = (counts[r.status] ?? 0) + 1;
  const v = verdictOf(g);
  const state = !v.last ? 'no verdict' : v.last.v.verdict === 'accepted' ? 'accepted' : 'unresolved';
  data[g] = { rows, counts, v, state };
}

// the comparison table is only allowed to say what the rows say
const bad = [];
for (const c of notes.comparison) for (const [n, want] of c.rows) {
  const r = data[c.group].rows[n - 1];
  if (!r || r.status !== want) bad.push(`${c.capability}: ${c.group} row ${n} is ${r?.status}, notes say ${want}`);
}
if (bad.length) { console.error('comparison table disagrees with the rows:\n  ' + bad.join('\n  ')); process.exit(1); }

const pin = 'fe3717f2e400010a4cd0e7dd4f294e7091c25625';
const sum = (k) => GROUPS.reduce((s, g) => s + (data[g].counts[k] ?? 0), 0);
const L = [];
L.push('# Layer contract: reSHape Script on SolidCraft');
L.push('');
L.push(`Measured on SolidCraft \`${pin}\` (engine 0.9.0, 2026-10-13), truck kernel, wasm build, with live OCCT and brep-rs as second oracles. Generated by \`contract/build-contract.mjs\` from the group files; every row cites its evidence in \`contract/<group>.json\`. Full row list: [LAYER-CONTRACT-ROWS.md](LAYER-CONTRACT-ROWS.md).`);
L.push('');
L.push('**Not yet measured on a newer kernel.** SolidCraft v0.16.2 (`5de48e916df2d659586a36b15c90ed05293a0954`) exists; this contract is for 0.9.0 only. Re-run it on v0.16.2 and diff (see "Re-running").');
L.push('');
L.push('## How to read this');
L.push('- **supported**: built and equal to an independent measure within the stated tolerance.');
L.push('- **refused**: not built; the student sees one plain sentence and the rest of the part is shown.');
L.push('- **wrong**: the kernel builds a solid that disagrees with the independent measure and nothing stops it. This is the dangerous class; every `wrong` row is listed below.');
L.push('- **unsupported**: the language or the translator has no route; no solid is claimed.');
L.push('');
L.push('**Guards are not shipped.** ' + notes.groupScope._shipping);
L.push('');
L.push('## Result by group');
L.push('');
L.push('| Group | Rows | supported | refused | wrong | unsupported | Final critic |');
L.push('|---|---:|---:|---:|---:|---:|---|');
for (const g of GROUPS) {
  const d = data[g], c = d.counts, rounds = d.v.all.length;
  L.push(`| ${g} | ${d.rows.length} | ${c.supported} | ${c.refused} | ${c.wrong} | ${c.unsupported} | ${d.state}${rounds > 1 ? ` after ${rounds} critic reviews` : ''} |`);
}
L.push(`| **total** | ${GROUPS.reduce((s, g) => s + data[g].rows.length, 0)} | ${sum('supported')} | ${sum('refused')} | ${sum('wrong')} | ${sum('unsupported')} | |`);
L.push('');
L.push(`Accepted: ${GROUPS.filter((g) => data[g].state === 'accepted').join(', ')}.`);
L.push(`Unresolved (still rejected after the two allowed fix rounds): ${GROUPS.filter((g) => data[g].state !== 'accepted').join(', ')}. The critics' live replays of sampled rows in these groups matched, but a critic found a silent wrong solid the guards do not cover, so the group as a whole is not accepted and the defects below are open.`);
L.push('');
L.push('## Capability against brep-rs');
L.push('');
L.push('The plan (Phase 1) lists these as what brep-rs supported: chamfer on convex edges, counterbore, countersink, groove, cone and sphere bores. That is taken from the plan and was not re-verified here. The SolidCraft column is measured, and every cell is checked against the cited row when this file is built.');
L.push('');
L.push('| Capability | SolidCraft layer (guarded) | Rows | Note |');
L.push('|---|---|---|---|');
for (const c of notes.comparison) L.push(`| ${c.capability} | ${c.rows.map(([, s]) => s).join(' / ')} | ${c.group} ${c.rows.map(([n]) => n).join(', ')} | ${c.note ?? ''} |`);
L.push('');
L.push('## Wrong rows (a solid is built and it is wrong)');
L.push('');
for (const g of GROUPS) {
  const w = data[g].rows.filter((r) => r.status === 'wrong'); if (!w.length) continue;
  L.push(`### ${g} (${w.length})`);
  for (const r of w) L.push(`- row ${r.n}: ${cut(r.feature, 260)}${r.note ? ` **${cut(r.note, 420)}**` : ''}`);
  L.push('');
}
L.push('## Open defects by group (from the last critic review)');
L.push('');
for (const g of GROUPS) {
  const d = data[g], last = d.v.last; if (!last) continue;
  L.push(`### ${g}: ${d.state} (${last.f})`);
  L.push(cut(last.v.summary, 600)); L.push('');
  for (const x of last.v.defects ?? []) L.push(`- ${x.severity}: ${cut(x.problem, 380)}`);
  if (last.v.notMeasured?.length) L.push(`- not measured by the critic: ${last.v.notMeasured.map((s) => cut(s, 120)).join('; ')}`);
  L.push('');
}
L.push('## Tolerances and thresholds');
L.push('- Each row states its own tolerance in its evidence text. The common bar for a curved solid against its independent measure is a relative volume error of 3e-4; planar parts use tighter bars set per group. Several group guards use thresholds that were chosen after seeing the probe data (for example the thin-web 1% of the bounding-box diagonal, the groove-to-wall 0.25 mm, the cone-chain limit of 3 move/turn steps, the keep depth max(2 mm, 0.035 R)); each such row says so and is re-checked only on fresh seeds.');
L.push('- A kernel swap touches the adapter only (AGENTS.md: one adapter seam). The guards and these rows are on our side of the seam; only `contract/` re-measurement changes with the kernel.');
L.push('- Phase 5 promotion thresholds (proposal, from the plan): re-evaluate the swap to SolidCore when boolean, primitive and blend are all above 80% green and a first end-to-end release exists.');
L.push('');
L.push('## Not measured');
L.push('- Anything in a real browser: this box has no playwright-cli or browser, so real page picking and the page\'s Worker time budget are carried from earlier rounds or marked not measured.');
L.push('- Groups were measured on a loaded box with a 1500 MB cap per kernel process; wall times are not claims.');
L.push('- Each critic opened a sample of rows and replayed 5 to 19 cases live; the rest rests on the builder scripts reproducing the rows and on the saved raw results.');
L.push('');
L.push('## Re-running');
L.push('```');
L.push('docs/spikes/solidcraft-referee/contract/run-contract.sh --rig [--commit <sha|tag>]   # build the wasm rig for a SolidCraft commit');
L.push('docs/spikes/solidcraft-referee/contract/run-contract.sh --check                      # rebuild rows from raw results, diff, regenerate this file (seconds)');
L.push('docs/spikes/solidcraft-referee/contract/run-contract.sh --measure --groups holes      # re-measure with the live rig, one command at a time under the memory cap');
L.push('node docs/spikes/solidcraft-referee/contract/build-contract.mjs --diff <dirOld> <dirNew>   # status changes between two measured contracts');
L.push('```');
L.push('Rig recipe and per-group commands: `contract/RIG.md`, `contract/contract-commands.json`. The pinned SolidCraft commit is in `run-contract.sh` (`PIN`). To measure v0.16.2 into a separate scratch directory: `run-contract.sh --rig --commit v0.16.2 --measure --out /tmp/contract-0.16.2`, then diff the two sets of group files with `--diff`.');
L.push('');
writeFileSync(path.join(OUTDIR, 'LAYER-CONTRACT.md'), L.join('\n'));

const R = ['# Layer contract: every row', '', `Generated by contract/build-contract.mjs. SolidCraft \`${pin}\`. Status and refusal sentence per row; the evidence text is in \`contract/<group>.json\`.`, ''];
for (const g of GROUPS) {
  R.push(`## ${g} (${data[g].state})`, '', '| # | status | feature | refusal sentence / note |', '|---:|---|---|---|');
  for (const r of data[g].rows) R.push(`| ${r.n} | ${r.status} | ${esc(cut(r.feature, 190))} | ${esc(cut(r.note ?? r.sentence ?? '', 240))} |`);
  R.push('');
}
writeFileSync(path.join(OUTDIR, 'LAYER-CONTRACT-ROWS.md'), R.join('\n'));
console.log(`wrote LAYER-CONTRACT.md and LAYER-CONTRACT-ROWS.md (${GROUPS.reduce((s, g) => s + data[g].rows.length, 0)} rows)`);
