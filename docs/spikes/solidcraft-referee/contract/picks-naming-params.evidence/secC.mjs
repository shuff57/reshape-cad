import { L, T, D, save } from './common.mjs';
const face = (feature, part) => ({ cause: 'primitive', feature, kind: 'face', part });
const box = (id, extra = {}) => ({ id, kind: 'box', size: [40, 30, 20], center: [5, -3, 2], ...extra });
const btw = (feature, a, b) => ({ cause: 'between', feature, kind: 'edge', of: [a, b] });
const fillet = (id, target, edge, style = 'fillet', size = 2) => ({ id, kind: 'fillet', target, size, style, edge });
const shell = (id, target, open, t = 2) => ({ id, kind: 'shell', target, thickness: t, open });
const draft = (id, target, f, angle = 5) => ({ id, kind: 'draft', target, angle, pull: 'z', neutral: 0, face: f });
const sk = (extra = {}) => ({ id: 'sk1', kind: 'sketch', plane: 'xy', offset: 0, points: [[0, 0], [40, 0], [40, 25], [0, 25]], ...extra });
const ex = (extra = {}) => ({ id: 'e1', kind: 'extrude', target: 'sk1', height: 12, ...extra });
const swept = (e, s, k) => ({ cause: 'swept', feature: e, kind: 'face', from: s, edge: k });
const cap = (e, end) => ({ cause: 'cap', feature: e, kind: 'face', end });
const V = (fs) => ({ version: 1, features: fs });
console.log('--- primitive (doc-level)'); 
await D('primitive box +x as shell open', V([box('b1'), shell('sh1', 'b1', face('b1', '+x'))]));
console.log('--- swept');
for (const k of [0,1,2,3]) await D(`swept edge${k} shell open`, V([sk(), ex(), shell('sh1', 'e1', swept('e1', 'sk1', k))]));
for (const k of [0,1,2,3]) await D(`swept edge${k} draft face`, V([sk(), ex(), draft('d1', 'e1', swept('e1','sk1',k))]));
for (const k of [0,1,2,3]) await D(`round between(cap top, swept${k})`, V([sk(), ex(), fillet('r1', 'e1', btw('e1', cap('e1','top'), swept('e1','sk1',k)))]));
for (const k of [0,2]) await D(`round between(cap bottom, swept${k})`, V([sk(), ex(), fillet('r1', 'e1', btw('e1', cap('e1','bottom'), swept('e1','sk1',k)))]));
await D('round between(swept0, swept1) vertical edge', V([sk(), ex(), fillet('r1', 'e1', btw('e1', swept('e1','sk1',0), swept('e1','sk1',1)))]));
await D('swept on xz-plane sketch', V([sk({plane:'xz'}), ex(), shell('sh1','e1',swept('e1','sk1',1))]));
await D('swept on offset sketch 5', V([sk({offset:5}), ex(), shell('sh1','e1',swept('e1','sk1',2))]));
await D('swept on circle sketch', V([{ id:'sk1', kind:'sketch', plane:'xy', offset:0, shape:'circle', points:[[ -10,0],[10,0]] }, ex(), shell('sh1','e1',swept('e1','sk1',0))]));
await D('swept on arc (bulge) sketch', V([sk({ bulges: {0: 0.5} }), ex(), shell('sh1','e1',swept('e1','sk1',0))]));
await D('swept on extrude midplane', V([sk(), ex({midplane:true}), shell('sh1','e1',swept('e1','sk1',1))]));
await D('swept on extrude taper', V([sk(), ex({taper:5}), shell('sh1','e1',swept('e1','sk1',1))]));
console.log('--- cap');
await D('cap top shell open', V([sk(), ex(), shell('sh1', 'e1', cap('e1','top'))]));
await D('cap bottom shell open', V([sk(), ex(), shell('sh1', 'e1', cap('e1','bottom'))]));
await D('cap top draft', V([sk(), ex(), draft('d1', 'e1', cap('e1','top'))]));
await D('cap on reversed extrude', V([sk(), ex({reversed:true}), shell('sh1','e1',cap('e1','top'))]));
console.log('--- rounded');
await D('rounded corner0 shell open', V([sk({ rounds: {0: 4} }), ex(), shell('sh1','e1',{cause:'rounded',feature:'e1',kind:'face',from:'sk1',corner:0})]));
await D('rounded corner0 draft', V([sk({ rounds: {0: 4} }), ex(), draft('d1','e1',{cause:'rounded',feature:'e1',kind:'face',from:'sk1',corner:0})]));
await D('round between(cap top, rounded0)', V([sk({ rounds: {0: 4} }), ex(), fillet('r1','e1',btw('e1', cap('e1','top'), {cause:'rounded',feature:'e1',kind:'face',from:'sk1',corner:0}))]));
save('resC1.json');
