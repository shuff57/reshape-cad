import { L, T, D, save } from './common.mjs';
const H = (t=10, p=10, d=4, at='[20, 15]') => `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, ${t});
const sk2 = sketch('top', ${t}); sk2.rect(${p}, ${p}, { at: ${at} });
const part = pocket(sk2, plate, ${d});
`;
console.log('--- pocket rim / wall');
await T('rim(sk2) round 1', H() + `round(part.rim(sk2), 1)`);
await T('rim(sk2) bevel 1', H() + `bevel(part.rim(sk2), 1)`);
for (const n of [1,2,3,4]) await T(`edge(top, wall ${n}) round 1`, H() + `round(part.edge('top', part.wall(sk2, ${n})), 1)`);
for (const [a,b] of [[1,2],[2,3],[3,4],[4,1]]) await T(`edge(wall ${a}, wall ${b}) round 1`, H() + `round(part.edge(part.wall(sk2, ${a}), part.wall(sk2, ${b})), 1)`);
await T('edge(wall1, wall3) opposite walls', H() + `round(part.edge(part.wall(sk2, 1), part.wall(sk2, 3)), 1)`);
await T('edge(wall1, wall1)', H() + `round(part.edge(part.wall(sk2, 1), part.wall(sk2, 1)), 1)`);
await T('wall(sk2, 5) out of range', H() + `round(part.edge('top', part.wall(sk2, 5)), 1)`);
await T('wall(sk2, 0)', H() + `round(part.edge('top', part.wall(sk2, 0)), 1)`);
await T('wall of non-pocket sketch', H() + `round(part.edge('top', part.wall(sk1, 1)), 1)`);
await T('edge(bottom, wall 1) (pocket floor edge?)', H() + `round(part.edge('bottom', part.wall(sk2, 1)), 1)`);
await T('edge(front, wall 1)', H() + `round(part.edge('front', part.wall(sk2, 1)), 1)`);
await T('rim thru pocket (deep 10)', H(10,10,10) + `round(part.rim(sk2), 1)`);
await T('rim off-centre pocket', H(10,8,4,'[12, 9]') + `round(part.rim(sk2), 1)`);
await T('rim round too big (r 5 in 10 pocket)', H() + `round(part.rim(sk2), 5)`);
await T('rim round 2 deep 4', H() + `round(part.rim(sk2), 2)`);
console.log('--- pocket shapes');
await T('triangle pocket rim', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.polygon([[12,8],[28,8],[20,22]]);
const part = pocket(sk2, plate, 4);
round(part.rim(sk2), 1)`);
await T('circle pocket rim', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.circle(12, { at: [20, 15] });
const part = pocket(sk2, plate, 4);
round(part.rim(sk2), 1)`);
await T('circle pocket wall1 edge(top,wall)', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.circle(12, { at: [20, 15] });
const part = pocket(sk2, plate, 4);
round(part.edge('top', part.wall(sk2, 1)), 1)`);
await T('rounded-corner pocket rim', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.rect(12, 12, { at: [20, 15] }); sk2.round(1, 2);
const part = pocket(sk2, plate, 4);
round(part.rim(sk2), 0.5)`);
await T('pocket from front plane: rim', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('front', 0); sk2.rect(10, 6, { at: [20, 5] });
const part = pocket(sk2, plate, 4);
round(part.rim(sk2), 1)`);
await T('pocket from front plane: edge(front, wall1)', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('front', 0); sk2.rect(10, 6, { at: [20, 5] });
const part = pocket(sk2, plate, 4);
round(part.edge('front', part.wall(sk2, 1)), 1)`);
await T('pocket depth is param: wall named', `const d = param('d', 4, {min:1,max:8})
const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.rect(10, 10, { at: [20, 15] });
const part = pocket(sk2, plate, d);
round(part.rim(sk2), 1)`);
await T('through pocket rim', `const sk1 = sketch('top'); sk1.rect(40, 30, { at: [20, 15] });
const plate = extrude(sk1, 10);
const sk2 = sketch('top', 10); sk2.rect(10, 10, { at: [20, 15] });
const part = pocket(sk2, plate, 4, { through: true });
round(part.rim(sk2), 1)`);
save('resD.json');
