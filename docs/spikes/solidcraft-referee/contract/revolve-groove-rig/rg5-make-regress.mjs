// Round 5: build cases-r5-regress.mjs = every GROOVE case that BUILT under the round-4 guard in the stored g0 result dirs (so a replay shows which of them the round-5 round-wall rule now refuses).
// usage: bun rg5-make-regress.mjs   (writes cases-r5-regress.mjs and r5-regress-before.json next to it / in ../revolve-groove-results/r5)
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url)); const RES = path.join(HERE, '..', 'revolve-groove-results');
const dirs = ['r3/old-g0', 'r3/r3-g0', 'r3/fz1-g0', 'r3/fz2-g0', 'r3/fz3-g0', 'r3/sl-g0', 'r4-graze', 'r3/cone-accuracy-g0'];
const seen = new Map(); const before = {};
for (const d of dirs) for (const f of readdirSync(path.join(RES, d)).filter((x) => x.endsWith('.json')).sort()) for (const r of JSON.parse(readFileSync(path.join(RES, d, f), 'utf8'))) {
  if (!/groove\(/.test(r.src ?? '')) continue; const fx = r.fixture ?? {}; const t = fx.invalid ? r.noOcct?.truck : fx.truck; if (!t || t.refused) continue;
  if (!seen.has(r.id)) { seen.set(r.id, r.src); before[r.id] = { dir: d, outcome: fx.outcome ?? null }; }
}
const cases = [...seen].map(([id, src]) => ({ id, src, tag: {} }));
writeFileSync(path.join(HERE, 'cases-r5-regress.mjs'), `// GENERATED by rg5-make-regress.mjs: groove cases that built under the round-4 guard (${cases.length}).\nexport const cases = ${JSON.stringify(cases, null, 1)};\n`);
mkdirSync(path.join(RES, 'r5'), { recursive: true }); writeFileSync(path.join(RES, 'r5', 'regress-before.json'), JSON.stringify(before, null, 1));
console.log(cases.length);
